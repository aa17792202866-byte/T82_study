# 6. 求100-999之间的所有水仙花数。
#    水仙花数是这个数的每一位上数字的立方和等于这个数本身，比如153=1^3+5^3+3^3=1+125+27=153
sum1 = 0
sxh = ''
for i in range(100,1000):
    bai = i // 100
    shi = i // 10 % 10
    ge = i % 10
    if i == bai**3 + shi**3 + pow(ge,3):
        sum1 += 1
        sxh += str(i) + ' '
print(f"水仙花数一共有{sum1}个,水仙花数分别是{sxh}")


