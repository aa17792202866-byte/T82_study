# 10. 有一个10米深的井，井底有只青蛙，青蛙每次向上爬5米后就会下滑3米，设计一个程序计算青蛙需要几次能爬到井外

# 定义变量，保存青蛙爬的次数和爬了多少米
cishu = 0
mi = 0

# 设置循环条件
while True:
    cishu += 1
    mi = mi + 5 - 3  # 错误点：直接将每次的净升高算为 2 米（提前扣除了下滑的 3 米）

    # 错误点：如果在循环末尾才判断，第 4 次爬到 11 米时会被强行扣成 8 米，导致判断不成立
    if mi >= 10:
        break

print(f'青蛙需要爬 {cishu} 次才能爬到井外')