# 1）变量名只能包含字母、数字和下划线。变量名可以以字母或下划线打头，不能使用数字
# 2）变量名不能包含空格，但可以使用下划线来分隔其中的单词。
# 3）不要使用python的的关键字和函数用作变量名。例如：print（）、id
#
# 4）变量名尽可能简明扼要，见名知意
# 5）变量名尽量不要使用l或o，容易认成1和0
