# 5. 格式化输出个人名片。
# 定义变量：姓名，公司，职位，电话，邮箱,工资(小数点后保留2位)。按照以下格式输出：
# **************************************************
# 公司名称 :
# 姓名(职位):
# 电话：
# 邮箱：
# 工资:
# **************************************************
# 注意：两行星星也要打印
# 要求使用三种方式分别打印名片
#方法一、先定义变量
comppany='某某科技有限公司'
name='张三'
job='测试组长'
phone='17867556768'
email='1976@qq.com'
salary=9878.889
star='*'*40
a=star
b=f'公司名称 :{comppany}'
c=f'姓名(职位):{name}({job})'
d=f'电话：{phone}'
e=f'邮箱：{email}'
f='工资: '
#方式一：普通输出
print(a,'\n',b,'\n',c,'\n',d,'\n',e,'\n',f,round(salary,2),'\n',a,sep='')
#方式二：格式化输出
print('%s\n%s\n%s\n%s\n%s\n%s%.2f\n%s'%(a,b,c,d,e,f,salary,a))
# 方式三：
print(f'{a}\n{b}\n{c}\n{d}\n{e}\n{f}{salary:.2f}\n{a}')